/** 受电弓的运动学与外形常量（**唯一来源**）。
 *
 * ## 依据（2026-11-11 按公开资料重标）
 * 蓝本 TSG19A（CRH380A 用）。可查到的硬参数只有下面这几条，其余是**按实拍比例反推的示意值**：
 *
 * | 项 | 值 | 来源 |
 * |---|---|---|
 * | 弓头长（含弓角） | 1950 mm | 王金花《动车组受电弓典型案例分析》（《集成电路应用》2019-06）；《从结构到原理，CRH380A 受电弓详解》 |
 * | 碳滑板长 | 1576 mm | 同上 |
 * | **两根滑板中心线距** | **约 597 mm** | 同上。第一版按 200mm 做，**是错的**：弓头因此显得又窄又薄 |
 * | 落弓高度 | 650 mm | 同上 |
 * | **支撑绝缘子数量** | **3 个** | 同上（"被刚性固定在三个专用绝缘子上"）；太原动车所《动车组受电弓》另有"2013 年起 TSG19A 全部更改为 **400mm 高**支持绝缘子" |
 * | 静态接触压力 | 80±10 N | 同上（本项目判据用 110±15，属样例虚构值，不改） |
 * | 弓头 / 滑板质量 | 117 kg（不含绝缘子与阀板） | 同上 |
 *
 * ## 为什么单独成文件
 * 弓头高度、接触压力、接触线位置这三组数，原来在建模与读数里各写一份，两边都注着
 * "改一处要改两处"。2026-11-10 已经因此踩过一次（读数与画面差 4cm）。这里收敛成一份。
 *
 * ## 摆动角是**反推值**，不是实测
 * 公开资料只给了两个端位高度（落弓 650mm、工作高度 2.9m 量级），没给摆角。
 * 标定方式：让两个端位同时成立，且上臂在落弓位为**负角**——
 * 实机收起时肘部最高、弓头落到肘点下方、搁在弓装配上。
 */

/** 杆长与铰点（米）。 */
export const PDIM = {
  /** 下臂长度（铰点到肘接） */
  lower: 1.5,
  /** 上臂长度（肘接到弓头托架） */
  upper: 1.28,
  /** 左右两臂的间距半径：两根下臂相距 0.92m */
  armX: 0.46,
  /** 上臂偏出下臂的距离。上臂夹在下臂**外侧**，收弓时两臂不穿插 */
  armOut: 0.12,
  /** 下臂铰点高度（相对车顶面）。必须高于底架梁顶面，否则销轴埋进梁里 */
  pivotY: 0.56,
  /** 下臂铰点前后位置（+Z 为车头方向，弓头在这一侧） */
  pivotZ: 0.6,
  /** 弓头半长：1950mm 的一半 */
  headHalf: 0.975,
  /** 碳滑板长度：1576mm */
  stripLen: 1.576,
  /** **两根滑板中心线距 597mm** 的一半。这是弓头最容易做错的一个数 */
  stripZ: 0.2985,
} as const

/**
 * 摆角（度）。`lo` = 落弓位，`hi` = 升到位。
 *
 * 上臂落弓角为**负**：实机收起时肘部最高、弓头落到肘点下方、搁在弓装配上。
 * 第一版写成 +10°，收弓后弓头吊在 0.84m，整台设备缩成一摞平板。
 */
export const PANGLES = {
  a1lo: 8,
  a1hi: 48,
  a2lo: -8,
  a2hi: 54,
} as const

/** 弓头悬挂（米）。三个数彼此锁定，改一个要重算 `WIRE_Y`。 */
export const PGAP = {
  /** 臂尖到弓头托架销接点的自由间隙 */
  free: 0.055,
  /** 弹簧最大压缩量 */
  maxComp: 0.045,
  /** 托架销点 → 碳滑板顶面 */
  headTop: 0.115,
} as const

const RAD = Math.PI / 180

/** 摆角随行程 p（0–1）线性插值。 */
export const armAngles = (p: number): { a1: number; a2: number } => ({
  a1: (PANGLES.a1lo + (PANGLES.a1hi - PANGLES.a1lo) * p) * RAD,
  a2: (PANGLES.a2lo + (PANGLES.a2hi - PANGLES.a2lo) * p) * RAD,
})

/** 臂尖（上臂顶端）的绝对高度。 */
export function armY(p: number): number {
  const { a1, a2 } = armAngles(p)
  return PDIM.pivotY + PDIM.lower * Math.sin(a1) + PDIM.upper * Math.sin(a2)
}

/** 臂尖的前后位置。升弓全程窜动约 10cm，仍在滑板宽度以内。 */
export function armZ(p: number): number {
  const { a1, a2 } = armAngles(p)
  return PDIM.pivotZ - PDIM.lower * Math.cos(a1) + PDIM.upper * Math.cos(a2)
}

/** 未受接触线约束时的滑板顶面高度。 */
export const freeTop = (p: number): number => armY(p) + PGAP.free + PGAP.headTop

const TOP_RAISED = freeTop(1)
/**
 * 接触线高度（相对车顶面）：由「满行程自由顶面 − 42mm 压缩量」反推，不写死。
 * 写死的话，任何人改一次杆长，"升到位 = 臂还在上行 + 弓头被挡住 + 压力到额定值"
 * 这三条会一起失效，而且不报错。
 */
export const WIRE_Y = TOP_RAISED - 0.042

/** 弓头当前被压下去多少（0–maxComp）。 */
export function compression(p: number): number {
  const over = freeTop(p) - WIRE_Y
  return over <= 0 ? 0 : Math.min(over, PGAP.maxComp)
}

/* -------------------------------------------------------------- 两根导杆 */

/**
 * 上导杆：**下臂 → 弓头支架**，作用是让滑板在整个工作高度上保持水平。
 *
 * 挂点不是随手定的：对全行程做过扫描，`f`（下臂上的比例）与弓头侧偏移这一组取值，
 * 使杆长全行程只变化 **0.5%**（1.32 → 1.33 m），所以可以画成**定长刚杆**，
 * 不用假装伸缩。
 */
export const UPPER_ROD = {
  /** 下臂上距铰点的比例 */
  f: 0.95,
  /** 弓头侧挂点相对托架销点的偏移（y, z），米 */
  offY: -0.05,
  offZ: 0.1,
} as const

/**
 * 下导杆：**底架 → 上臂**，用于调整最大升弓高度与滑板轨迹。
 *
 * ## 为什么做成**可伸缩的导向杆**而不是定长连杆
 * 公开资料没给两个挂点，只写"接在上臂一端和底架上"。用现有摆角曲线实测：
 * 底架到上臂的任何挂法，全行程杆长都会变化 90% 以上（0.73 → 1.42 m 量级）——
 * 也就是说它**不是**定长连杆，而是一根在导向套里滑动的杆（"导杆"这个名字本身
 * 就是这个意思）。所以按**套管 + 滑杆**建模：外套挂底架，滑杆挂上臂，随行程抽出。
 * 这样两端口都贴在实际挂点上，不会有任何一根杆被"拉长"。
 *
 * 若要把它做成定长四连杆，必须把 a2 改成由约束解出的函数（1 自由度五杆机构），
 * 那会改掉 `armY(p)` 与读数口径——已登记待办，不在本轮。
 */
export const LOWER_ROD = {
  /** 底架侧铰点（y, z），米 */
  base: { y: 0.56, z: 0.08 },
  /** 上臂上的挂点比例（从肘点向弓头方向） */
  s: 0.42,
} as const
